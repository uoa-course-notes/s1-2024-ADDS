int Reverser::reverseDigit(int value){
    if (value < 0) return -1;
        // throw std::invalid_argument("Value must at least be 0.");
    
    
    return value;
}



std::string Reverser::reverseString(std::string characters){
    if (characters == "") return "ERROR";
    return characters;
}